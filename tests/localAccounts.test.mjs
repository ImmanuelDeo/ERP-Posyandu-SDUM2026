import assert from 'node:assert/strict';
import * as accounts from '../src/services/localAccounts.js';
const store = new Map();
globalThis.localStorage = { getItem: (key) => store.get(key) ?? null, setItem: (key, value) => store.set(key, value) };
const password = 'test-only-long-secret';
const request = { username: 'parent.test', motherName: 'Ibu Siti Aminah', childName: 'Anak Pengujian', birthDate: '2024-04-14' };
const child = { id: 'c1', namaOrtu: 'siti aminah', nama: 'ANAK PENGUJIAN', tglLahir: request.birthDate, history: [] };
const db = { arca: { children: [child] }, other: { children: [{ ...child, id: 'other-child' }] } };
assert.equal(accounts.hasLocalAdmin(), false);
await assert.rejects(accounts.loginLocalAdmin('admin', 'admin123'));
await accounts.setupLocalAdmin('petugas.test', password);
assert.equal(accounts.hasLocalAdmin(), true);
await assert.rejects(accounts.setupLocalAdmin('second.admin', password));
const parent = await accounts.registerLocalParent(request, password);
assert.equal(parent.status, 'pending');
assert.equal(parent.childId, null);
assert.equal(parent.hash, undefined);
assert.equal([...store.values()].some((value) => value.includes(password)), false);
await assert.rejects(accounts.registerLocalParent({ ...request, username: 'PARENT.TEST' }, password));
await assert.rejects(accounts.registerLocalParent({ ...request, username: 'bad.date', birthDate: '2024-02-30' }, password));
await assert.rejects(accounts.registerLocalParent({ ...request, username: 'bad.pass' }, 'short'));
assert.equal(accounts.matchesParentRequest(request, child), true);
assert.equal(accounts.matchesParentRequest({ ...request, motherName: 'Siti' }, child), false);
assert.equal(accounts.matchesParentRequest({ ...request, childName: 'Anak' }, child), false);
assert.equal(accounts.matchesParentRequest({ ...request, birthDate: '2024-04-15' }, child), false);
await accounts.loginLocalParent(request.username, password);
assert.equal(accounts.resolveLocalParent(parent.id, db), null);
assert.throws(() => accounts.approveLocalParent(parent.id, 'arca', child.id, db));
await accounts.loginLocalAdmin('petugas.test', password);
assert.equal(accounts.listPendingParents().length, 1);
assert.throws(() => accounts.approveLocalParent(parent.id, 'missing', child.id, db));
assert.throws(() => accounts.approveLocalParent(parent.id, 'arca', child.id, { arca: { children: [child, { ...child, id: 'duplicate' }] } }));
accounts.approveLocalParent(parent.id, 'arca', child.id, db);
await accounts.loginLocalParent(request.username, password);
assert.equal(accounts.resolveLocalParent(parent.id, db).child.id, child.id);
assert.equal(accounts.resolveLocalParent(parent.id, { other: db.other }), null);
assert.equal(accounts.resolveLocalParent(parent.id, { arca: { children: [{ ...child, namaOrtu: 'Different Mother' }] } }), null);
accounts.logoutLocalAccount();
assert.equal(accounts.resolveLocalParent(parent.id, db), null);
await assert.rejects(accounts.loginLocalParent(request.username, 'wrong-long-password'));
const before = [...store.values()][0];
localStorage.setItem = () => { throw new Error('quota'); };
await assert.rejects(accounts.registerLocalParent({ ...request, username: 'quota.test' }, password), /quota/);
assert.equal([...store.values()][0], before);
console.log('localAccounts: registration, hashing, validation, pending access, approval, tenant scope, stale links, logout, storage failure passed');
